from __future__ import annotations

from typing import Any, Protocol
from .models import GameState


class RngPort(Protocol):
    def random(self) -> float: ...
    def choice(self, seq: list[tuple[int, int]]) -> tuple[int, int]: ...


class SpawnPolicyPort(Protocol):
    def next_tile(self, rng: RngPort) -> int: ...


class CachePort(Protocol):
    def get(self, key: str) -> Any | None: ...
    def set(self, key: str, value: Any, ttl_seconds: float | None = None) -> None: ...
    def delete(self, key: str) -> None: ...
    def stats(self) -> dict[str, int]: ...


class GameStorePort(Protocol):
    def save(self, state: GameState) -> None: ...
    def load(self, game_id: str) -> GameState | None: ...
    def delete(self, game_id: str) -> None: ...


class LeaderboardPort(Protocol):
    def update_score(self, player_id: str, score: int) -> int: ...
    def get_best_score(self, player_id: str) -> int: ...
    def top(self, limit: int = 10) -> list[tuple[str, int]]: ...


class RequestJournalPort(Protocol):
    def append(self, record: dict[str, Any]) -> None: ...
    def list_all(self) -> list[dict[str, Any]]: ...


class LoggerPort(Protocol):
    def info(self, event: str, **fields: Any) -> None: ...
    def warning(self, event: str, **fields: Any) -> None: ...
    def error(self, event: str, **fields: Any) -> None: ...


class MetricsPort(Protocol):
    def inc(self, name: str, value: int = 1) -> None: ...
    def gauge(self, name: str, value: float) -> None: ...
    def observe_ms(self, name: str, ms: float) -> None: ...
    def snapshot(self) -> dict[str, Any]: ...
